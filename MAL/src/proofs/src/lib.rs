// VERIFIER
// ═══════════════════════════════════════════════════════════
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum VerifyResult {
    Valid,
    Invalid(String),
    Warning(String),
}
pub fn verify_proof(proof: &Proof) -> VerifyResult {
    if proof.name.is_empty() {
        return VerifyResult::Invalid("empty theorem name".to_string());
    }
    if proof.steps.is_empty() {
        return VerifyResult::Invalid("empty proof".to_string());
    }
    if !is_well_formed(&proof.statement) {
        return VerifyResult::Invalid("ill-formed statement".to_string());
    }
    for step in &proof.steps {
        if let ProofStep::Assumption(name) = step {
            if name.is_empty() {
                return VerifyResult::Invalid("empty assumption name".to_string());
            }
        }
    }
    VerifyResult::Valid
}
fn is_well_formed(term: &Term) -> bool {
    match term {
        Term::Var(name) => !name.is_empty(),
        Term::App(f, x) => is_well_formed(f) && is_well_formed(x),
        Term::Lambda(_, body) => is_well_formed(body),
        Term::Pi(_, ty, body) => is_well_formed(ty) && is_well_formed(body),
        Term::Type(_) | Term::Nat(_) | Term::Str(_) | Term::Bool(_) => true,
        Term::Eq(a, b) | Term::Impl(a, b) | Term::And(a, b) | Term::Or(a, b) => {
            is_well_formed(a) && is_well_formed(b)
        }
        Term::Not(a) => is_well_formed(a),
        Term::Forall(_, ty, body) | Term::Exists(_, ty, body) => {
            is_well_formed(ty) && is_well_formed(body)
        }
    }
}
