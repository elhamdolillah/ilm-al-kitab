// AGDA EXPORTER
// ═══════════════════════════════════════════════════════════
pub struct AgdaExporter;
impl AgdaExporter {
    pub fn export(proof: &Proof) -> String {
        let mut out = format!("-- {}\n-- Exported from MAL: {}\n\n{} : {}\n{} = {}\n",
            proof.description, proof.name, proof.name,
            Self::term(&proof.statement), proof.name,
            Self::proof_term(proof));
        out
    }
    pub fn export_module(name: &str, proofs: &[Proof]) -> String {
        let mut out = format!("-- {} Module\nmodule {} where\n\n", name, name);
        for p in proofs {
            out.push_str(&Self::export(p));
            out.push_str("\n");
        }
        out
    }
    fn term(t: &Term) -> String {
        match t {
            Term::Var(n) => n.clone(),
            Term::App(f, x) => format!("({} {})", Self::term(f), Self::term(x)),
            Term::Lambda(x, b) => format!("(λ {} → {})", x, Self::term(b)),
            Term::Pi(x, ty, b) => format!("({} : {}) → {}", x, Self::term(ty), Self::term(b)),
            Term::Type(n) => if *n == 0 { "Set".to_string() } else { format!("Set{}", n) },
            Term::Nat(n) => n.to_string(),
            Term::Str(s) => format!("\"{}\"", s),
            Term::Bool(b) => if *b { "true" } else { "false" }.to_string(),
            Term::Eq(a, b) => format!("({} ≡ {})", Self::term(a), Self::term(b)),
            Term::Impl(a, b) => format!("({} → {})", Self::term(a), Self::term(b)),
            Term::And(a, b) => format!("({} × {})", Self::term(a), Self::term(b)),
            Term::Or(a, b) => format!("({} ⊎ {})", Self::term(a), Self::term(b)),
            Term::Not(a) => format!("(¬ {})", Self::term(a)),
            Term::Forall(x, ty, b) => format!("∀ ({} : {}) → {}", x, Self::term(ty), Self::term(b)),
            Term::Exists(x, _ty, b) => format!("∃ λ {} → {}", x, Self::term(b)),
        }
    }
    fn proof_term(proof: &Proof) -> String {
        let mut r = String::new();
        for (i, s) in proof.steps.iter().enumerate() {
            if i > 0 { r.push(' '); }
            r.push_str(&Self::step(s));
        }
        if r.is_empty() { r = "?".to_string(); }
        r
    }
    fn step(s: &ProofStep) -> String {
        match s {
            ProofStep::Intro(x) => format!("λ {}", x),
            ProofStep::Apply(n) => n.clone(),
            ProofStep::Assumption(n) => n.clone(),
            ProofStep::Reflexivity => "refl".to_string(),
            ProofStep::Symmetry => "sym".to_string(),
            ProofStep::Transitivity => "trans".to_string(),
            ProofStep::Split => "λ { (a , b) → a , b }".to_string(),
            ProofStep::Left => "inj₁".to_string(),
            ProofStep::Right => "inj₂".to_string(),
            ProofStep::Induction(_) | ProofStep::Cases(_) => "?".to_string(),
            ProofStep::Rewrite(e) => format!("subst {}", e),
            ProofStep::Simplify => "id".to_string(),
            ProofStep::Exact(t) => Self::term(t),
        }
    }
}
