// PROOF AST
// ═══════════════════════════════════════════════════════════
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Term {
    Var(String),
    App(Box<Term>, Box<Term>),
    Lambda(String, Box<Term>),
    Pi(String, Box<Term>, Box<Term>),
    Type(usize),
    Nat(usize),
    Str(String),
    Bool(bool),
    Eq(Box<Term>, Box<Term>),
    Impl(Box<Term>, Box<Term>),
    And(Box<Term>, Box<Term>),
    Or(Box<Term>, Box<Term>),
    Not(Box<Term>),
    Forall(String, Box<Term>, Box<Term>),
    Exists(String, Box<Term>, Box<Term>),
}
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ProofStep {
    Intro(String),
    Apply(String),
    Assumption(String),
    Reflexivity,
    Symmetry,
    Transitivity,
    Split,
    Left,
    Right,
    Induction(String),
    Cases(String),
    Rewrite(String),
    Simplify,
    Exact(Term),
}
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Proof {
    pub name: String,
    pub statement: Term,
    pub steps: Vec<ProofStep>,
    pub description: String,
}
impl Proof {
    pub fn new(name: String, statement: Term, steps: Vec<ProofStep>) -> Self {
        Self { name, statement, steps, description: String::new() }
    }
    pub fn with_description(mut self, desc: &str) -> Self {
        self.description = desc.to_string();
        self
    }
}
