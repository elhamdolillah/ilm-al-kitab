// COQ EXPORTER
// ═══════════════════════════════════════════════════════════
pub struct CoqExporter;
impl CoqExporter {
    pub fn export(proof: &Proof) -> String {
        let mut out = String::new();
        out.push_str(&format!("(* {} *)\n", proof.description));
        out.push_str(&format!("(* Exported from MAL proof: {} *)\n\n", proof.name));
        out.push_str(&format!("Theorem {} : {}.\n", proof.name, Self::term(&proof.statement)));
        out.push_str("Proof.\n");
        for step in &proof.steps {
            out.push_str(&format!("  {}.\n", Self::step(step)));
        }
        out.push_str("Qed.\n");
        out
    }
    pub fn export_module(name: &str, proofs: &[Proof]) -> String {
        let mut out = format!("(* {} Module *)\n(* Generated by MAL *)\n\nModule {}.\n\n", name, name);
        for p in proofs {
            out.push_str(&Self::export(p));
            out.push_str("\n");
        }
        out.push_str(&format!("End {}.\n", name));
        out
    }
    fn term(t: &Term) -> String {
        match t {
            Term::Var(n) => n.clone(),
            Term::App(f, x) => format!("({} {})", Self::term(f), Self::term(x)),
            Term::Lambda(x, b) => format!("(fun {} => {})", x, Self::term(b)),
            Term::Pi(x, ty, b) => format!("(forall ({} : {}), {})", x, Self::term(ty), Self::term(b)),
            Term::Type(n) => format!("Type{}", n),
            Term::Nat(n) => n.to_string(),
            Term::Str(s) => format!("\"{}\"", s),
            Term::Bool(b) => if *b { "true" } else { "false" }.to_string(),
            Term::Eq(a, b) => format!("({} = {})", Self::term(a), Self::term(b)),
            Term::Impl(a, b) => format!("({} -> {})", Self::term(a), Self::term(b)),
            Term::And(a, b) => format!("({} /\\ {})", Self::term(a), Self::term(b)),
            Term::Or(a, b) => format!("({} \\/ {})", Self::term(a), Self::term(b)),
            Term::Not(a) => format!("(~ {})", Self::term(a)),
            Term::Forall(x, ty, b) => format!("(forall ({} : {}), {})", x, Self::term(ty), Self::term(b)),
            Term::Exists(x, ty, b) => format!("(exists ({} : {}), {})", x, Self::term(ty), Self::term(b)),
        }
    }
    fn step(s: &ProofStep) -> String {
        match s {
            ProofStep::Intro(x) => format!("intro {}", x),
            ProofStep::Apply(n) => format!("apply {}", n),
            ProofStep::Assumption(n) => format!("exact {}", n),
            ProofStep::Reflexivity => "reflexivity".to_string(),
            ProofStep::Symmetry => "symmetry".to_string(),
            ProofStep::Transitivity => "transitivity".to_string(),
            ProofStep::Split => "split".to_string(),
            ProofStep::Left => "left".to_string(),
            ProofStep::Right => "right".to_string(),
            ProofStep::Induction(x) => format!("induction {}", x),
            ProofStep::Cases(x) => format!("destruct {}", x),
            ProofStep::Rewrite(e) => format!("rewrite {}", e),
            ProofStep::Simplify => "simpl".to_string(),
            ProofStep::Exact(t) => format!("exact ({})", Self::term(t)),
        }
    }
    fn parse_step(tactic: &str) -> Option<ProofStep> {
        let t = tactic.trim();
        if t == "reflexivity" { Some(ProofStep::Reflexivity) }
        else if t == "symmetry" { Some(ProofStep::Symmetry) }
        else if t == "transitivity" { Some(ProofStep::Transitivity) }
        else if t == "split" { Some(ProofStep::Split) }
        else if t == "left" { Some(ProofStep::Left) }
        else if t == "right" { Some(ProofStep::Right) }
        else if t == "simpl" { Some(ProofStep::Simplify) }
        else if t.starts_with("intro ") { Some(ProofStep::Intro(t[6..].to_string())) }
        else if t.starts_with("apply ") { Some(ProofStep::Apply(t[6..].to_string())) }
        else if t.starts_with("exact ") { Some(ProofStep::Assumption(t[6..].to_string())) }
        else if t.starts_with("induction ") { Some(ProofStep::Induction(t[10..].to_string())) }
        else if t.starts_with("destruct ") { Some(ProofStep::Cases(t[9..].to_string())) }
        else if t.starts_with("rewrite ") { Some(ProofStep::Rewrite(t[8..].to_string())) }
        else { None }
    }
    pub fn import(code: &str) -> Option<Proof> {
        let mut name = String::new();
        let mut stmt_str = String::new();
        let mut steps = Vec::new();
        for line in code.lines() {
            let l = line.trim();
            if l.starts_with("Theorem ") {
                if let Some(colon) = l.find(':') {
                    name = l[8..colon].trim().to_string();
                    stmt_str = l[colon+1..].trim().trim_end_matches('.').to_string();
                }
            } else if l == "Proof." || l == "Qed." {
                continue;
            } else if l.ends_with('.') && !l.starts_with("(*") {
                let tac = l.trim_end_matches('.');
                if let Some(step) = Self::parse_step(tac) {
                    steps.push(step);
                }
            }
        }
        if name.is_empty() {
            return None;
        }
        let statement = if stmt_str.is_empty() {
            Term::Var("_".to_string())
        } else {
            Term::Var(stmt_str)
        };
        Some(Proof::new(name, statement, steps))
    }
}
