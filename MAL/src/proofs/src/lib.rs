#[cfg(test)]
mod tests {
    use super::*;
    fn build_refl_proof() -> Proof {
        let stmt = Term::Forall(
            "n".to_string(),
            Box::new(Term::Type(0)),
            Box::new(Term::Eq(
                Box::new(Term::Var("n".to_string())),
                Box::new(Term::Var("n".to_string())),
            )),
        );
        Proof::new("reflexivity_example".to_string(), stmt, vec![
            ProofStep::Intro("n".to_string()),
            ProofStep::Reflexivity,
        ]).with_description("Every term equals itself")
    }
    fn build_impl_proof() -> Proof {
        let stmt = Term::Impl(
            Box::new(Term::Var("P".to_string())),
            Box::new(Term::Var("P".to_string())),
        );
        Proof::new("identity_impl".to_string(), stmt, vec![
            ProofStep::Intro("p".to_string()),
            ProofStep::Assumption("p".to_string()),
        ]).with_description("P implies P")
    }
    #[test]
    fn test_coq_export() {
        let p = build_refl_proof();
        assert_eq!(verify_proof(&p), VerifyResult::Valid);
        let coq = CoqExporter::export(&p);
        assert!(coq.contains("Theorem reflexivity_example"));
        assert!(coq.contains("Proof."));
        assert!(coq.contains("intro n"));
        assert!(coq.contains("reflexivity"));
        assert!(coq.contains("Qed."));
        let proofs = vec![build_refl_proof(), build_impl_proof()];
        let module = CoqExporter::export_module("TestModule", &proofs);
        assert!(module.contains("Module TestModule"));
        assert!(module.contains("End TestModule"));
    }
    #[test]
    fn test_lean_export() {
        let p = build_refl_proof();
        let lean = LeanExporter::export(&p);
        assert!(lean.contains("theorem reflexivity_example"));
        assert!(lean.contains("by"));
        assert!(lean.contains("intro n"));
        assert!(lean.contains("rfl"));
        assert!(lean.contains("∀"));
        let proofs = vec![build_refl_proof()];
        let module = LeanExporter::export_module("TestNS", &proofs);
        assert!(module.contains("namespace TestNS"));
        assert!(module.contains("end TestNS"));
    }
    #[test]
    fn test_agda_export() {
        let p = build_refl_proof();
        let agda = AgdaExporter::export(&p);
        assert!(agda.contains("reflexivity_example :"));
        assert!(agda.contains("reflexivity_example ="));
        assert!(agda.contains("λ n"));
        assert!(agda.contains("refl"));
        assert!(agda.contains("→"));
        assert!(agda.contains("≡"));
        let proofs = vec![build_refl_proof()];
        let module = AgdaExporter::export_module("TestMod", &proofs);
        assert!(module.contains("module TestMod where"));
    }
    #[test]
    fn test_roundtrip() {
        let original = build_refl_proof();
        assert_eq!(verify_proof(&original), VerifyResult::Valid);
        assert_eq!(original.name, "reflexivity_example");
        assert_eq!(original.steps.len(), 2);
        let coq = CoqExporter::export(&original);
        let reimported = CoqExporter::import(&coq);
        assert!(reimported.is_some());
        let imp = reimported.unwrap();
        assert_eq!(imp.name, "reflexivity_example");
        assert_eq!(imp.steps.len(), 2);
        assert_eq!(imp.steps[0], ProofStep::Intro("n".to_string()));
        assert_eq!(imp.steps[1], ProofStep::Reflexivity);
        assert_eq!(verify_proof(&imp), VerifyResult::Valid);
    }
    #[test]
    fn test_verification() {
        assert_eq!(verify_proof(&build_refl_proof()), VerifyResult::Valid);
        let empty_name = Proof::new(String::new(), Term::Var("x".to_string()), vec![ProofStep::Reflexivity]);
        assert!(matches!(verify_proof(&empty_name), VerifyResult::Invalid(_)));
        let empty_steps = Proof::new("t".to_string(), Term::Var("x".to_string()), vec![]);
        assert!(matches!(verify_proof(&empty_steps), VerifyResult::Invalid(_)));
        let empty_assumption = Proof::new("t".to_string(), Term::Var("x".to_string()),
            vec![ProofStep::Assumption(String::new())]);
        assert!(matches!(verify_proof(&empty_assumption), VerifyResult::Invalid(_)));
        assert!(is_well_formed(&Term::Var("x".to_string())));
        assert!(is_well_formed(&Term::Nat(42)));
        assert!(!is_well_formed(&Term::Var(String::new())));
        let complex = Term::Forall(
            "n".to_string(),
            Box::new(Term::Type(0)),
            Box::new(Term::Impl(
                Box::new(Term::Eq(Box::new(Term::Var("n".to_string())), Box::new(Term::Nat(0)))),
                Box::new(Term::Var("P".to_string())),
            )),
        );
        assert!(is_well_formed(&complex));
    }
}
